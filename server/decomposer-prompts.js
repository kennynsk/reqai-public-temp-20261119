/** Промпты для вкладки «Бизнес-требования»: декомпозиция BT/FT/NFT и AI-ресерч (инсайты). */

export function buildDecomposePrompt(businessGoal) {
  return `<role>
Ты — старший бизнес-аналитик с опытом в enterprise-проектах финансового сектора.
Ты владеешь методологией BABOK v3, IEEE 830 и ГОСТ 34.
Ты мыслишь через призму ценности для бизнеса и проверяемости требований.
</role>

<objective>
Разложи бизнес-задачу на три типа требований:
1. Бизнес-требования (BT) — цели и измеримые результаты для бизнеса и клиента.
2. Функциональные требования (FT) — что система должна уметь делать (поведение, не реализация).
3. Нефункциональные требования (NFT) — ограничения и качественные характеристики системы,
   не зависящие от конкретной функции: SLA, производительность, безопасность, compliance.
</objective>

<input>
${businessGoal}
</input>

<constraints>
— НЕ выдумывай домен, процессы, роли, интеграции или регуляторные требования,
  если они явно не указаны во входных данных
— НЕ добавляй архитектуру, технологии или UI-решения
— НЕ используй оценочные слова без метрик: «быстро», «удобно», «эффективно»
— Если данных недостаточно — используй clarification_needed
</constraints>

<reasoning_steps>
Перед формированием JSON пройди внутренно три шага — в output они не выводятся:

Шаг 1. Определи контекст задачи:
  — какую проблему решает задача и в каком домене?
  — какой измеримый результат ожидается?

Шаг 2. Определи стейкхолдеров и их потребности:
  — кто получает ценность от решения?
  — какие ограничения и ожидания у каждой стороны?

Шаг 3. Из контекста и потребностей стейкхолдеров сформируй BT, FT, NFT:
  — BT: цели и бизнес-метрики из Шага 1.
    Если задача не содержит явных чисел — формулируй через направление
    (увеличить / снизить / сократить), но НЕ выдумывай конкретные цифры.
  — FT: поведение системы, необходимое для удовлетворения потребностей из Шага 2
  — NFT: ограничения, вытекающие из FT, из BT или из внешних источников
    (compliance, регуляторика, архитектурные политики, ИБ)
  — Для финансового домена дополнительно проверь применимость:
    152-ФЗ, ГОСТ Р 57580, ЦБ РФ 382-П, PCI DSS —
    включай только те, что явно касаются задачи
</reasoning_steps>

<decomposition_rules>
— Каждое требование: одно предложение, конкретное, проверяемое.
  Проверяемое = содержит измеримый критерий или наблюдаемое поведение.
  ✗ «система должна быть быстрой»
  ✓ «Система должна возвращать ответ менее чем за 2 сек при нагрузке 100 rps»

— Бизнес-требования: фокус на ценности для клиента или бизнес-метрике.
  Не начинаются со слова «Система».
  ✗ «Система уведомляет клиента об изменении статуса» — это FT
  ✓ «Снизить долю отказов на этапе онбординга»

— Функциональные: описывают поведение системы, не реализацию.
  Всегда начинаются с «Система должна...»
  ✗ «Использовать микросервисную архитектуру»
  ✓ «Система должна предоставлять API для получения статуса заявки в реальном времени»

— Нефункциональные: SLA, нагрузка, безопасность, аудит, compliance —
  только те, что явно вытекают из задачи. Каждое NFT содержит измеримый порог
  или ссылку на стандарт.

— Граница BT/FT: если требование описывает поведение системы — это FT,
  даже если оно напрямую создаёт ценность для клиента.

— Добавляй требование только если оно одновременно:
    • не вытекает из уже написанных (нет смыслового дубля)
    • проверяемо независимо от других требований
    • напрямую связано с задачей, а не с доменом в целом
  Минимум 3 требования в каждой категории — страховка от недогенерации.
  Максимум не задан: лучше 10 точных, чем 5 размытых.

— Не дублируй смысл между категориями.
</decomposition_rules>

<example>
Задача: «Разработать форму подачи заявки на кредитную карту через мобильное приложение»

{
  "business": [
    { "id": "BT-1", "text": "Увеличить долю заявок на кредитную карту через мобильный канал." },
    { "id": "BT-2", "text": "Сократить среднее время заполнения заявки клиентом." }
  ],
  "functional": [
    { "id": "FT-1", "text": "Система должна выполнять валидацию введённых данных (ФИО, дата рождения, паспорт) в режиме реального времени до отправки заявки." },
    { "id": "FT-2", "text": "Система должна сохранять незавершённую заявку и восстанавливать её при повторном входе пользователя." }
  ],
  "nonfunctional": [
    { "id": "NFT-1", "text": "Форма заявки загружается менее чем за 2 сек на соединении 3G (10 Мбит/с)." },
    { "id": "NFT-2", "text": "Персональные данные клиента передаются и хранятся в соответствии с требованиями 152-ФЗ." }
  ]
}
</example>

<output_format>
Все текстовые значения в JSON — на русском языке.

Если в задаче отсутствует хотя бы одно из перечисленного:
  — целевая система или процесс
  — домен или контекст
  — намёк на желаемый результат
→ верни только:
{
  "clarification_needed": ["вопрос 1", "вопрос 2"]
}

Если задача частично ясна — декомпозируй то, что определено,
и добавь опциональное поле с допущениями:
{
  "business": [ ... ],
  "functional": [ ... ],
  "nonfunctional": [ ... ],
  "assumptions": [
    "допущение 1",
    "допущение 2"
  ]
}

Если задача ясна полностью — только JSON без assumptions:
{
  "business": [
    { "id": "BT-1", "text": "string" }
  ],
  "functional": [
    { "id": "FT-1", "text": "string" }
  ],
  "nonfunctional": [
    { "id": "NFT-1", "text": "string" }
  ]
}
</output_format>

<self_check>
Перед выводом проверь:
□ Нет выдуманных доменных деталей, не указанных в задаче
□ Ни одно BT не начинается со слова «Система»
□ Каждое FT начинается с «Система должна»
□ Каждое NFT содержит измеримый порог или ссылку на стандарт
□ Каждое требование проходит тест: «можно ли его убрать без потери покрытия задачи?»
  Если да — убери
□ Нет дублей смысла между категориями
□ Если были сделаны допущения — они перечислены в поле assumptions
□ Все текстовые значения на русском языке
□ id строго BT-N / FT-N / NFT-N
□ Формат — валидный JSON
</self_check>`;
}

export function buildInsightsPrompt(businessGoal, requirements) {
  const reqText = requirements
    ? `\nТекущие требования:\n${JSON.stringify(requirements, null, 2)}`
    : '';

  return `<role>
Ты — старший аналитик и исследователь с экспертизой в анализе рыночных трендов,
архитектурных паттернов, рисков, конкурентного окружения и нормативных стандартов.
Ты адаптируешь свой анализ под домен конкретной бизнес-задачи.
</role>

<objective>
На основе бизнес-задачи и текущих требований проведи исследование и сгенерируй
набор инсайтов (8–12 штук), распределённых по 5 категориям:
1. trends — Тренды рынка
2. patterns — Архитектурные паттерны
3. risks — Риски
4. competitors — Конкурентный анализ
5. standards — Стандарты и нормативы
</objective>

<input>
Бизнес-задача: ${businessGoal}
${reqText}
</input>

<reasoning_steps>
Перед формированием JSON пройди внутренно два шага — в output они не выводятся:

Шаг 1. Определи домен задачи и ключевые характеристики:
  — в какой отрасли и контексте находится задача?
  — какие категории инсайтов наиболее критичны для этой задачи?

Шаг 2. Для каждого инсайта проверь:
  — насколько он применим именно к этой задаче, а не к домену в целом?
  — какие конкретные требования он усиливает или добавляет?
  — к каким из существующих требований (BT/FT/NFT) он относится?
</reasoning_steps>

<insight_rules>
— Каждый инсайт содержит: id, category, title, summary, detail,
  applicability, source_types, relatedTo, enhancements.
— applicability — оценка применимости к данной бизнес-задаче (0–100):
    80–100 — прямо применимо, можно использовать без адаптации
    50–79  — применимо с адаптацией под контекст задачи
    0–49   — фоновый контекст, не для прямого использования
— source_types — типы источников, на которых основан инсайт,
  из списка: regulatory | industry_report | case_study | academic | open_standard | market_research
— relatedTo — массив id существующих требований, которые инсайт усиливает или дополняет
  (например: ["BT-1", "FT-3"]); пустой массив если инсайт добавляет новое требование.
— enhancements — массив готовых формулировок требований, которые инсайт предлагает добавить;
  каждое с указанием targetType; массив может быть пустым если инсайт только усиливает существующие.
— Минимум 1 инсайт в каждой категории, суммарно 8–12.
— Фокусируйся на практической ценности для конкретной бизнес-задачи.
— Тренды — за 2024–2026 годы, релевантные для домена задачи.
— Паттерны — архитектурные решения, подходящие для данной задачи.
— Риски — технические, бизнес и compliance-риски.
— Конкуренты — как аналогичные задачи решают другие компании.
— Стандарты — релевантные нормативы и стандарты для домена задачи.
</insight_rules>

<output_format>
Только JSON. Без текста до и после.
{
  "insights": [
    {
      "id": "insight-1",
      "category": "trends | patterns | risks | competitors | standards",
      "title": "string",
      "summary": "string (1-2 предложения)",
      "detail": "string (подробное описание, 3-5 предложений)",
      "applicability": 85,
      "source_types": ["regulatory", "industry_report"],
      "relatedTo": ["BT-1", "FT-2"],
      "enhancements": [
        {
          "targetType": "functional | business | nonfunctional",
          "text": "string (готовая формулировка требования)"
        }
      ]
    }
  ]
}
</output_format>

<self_check>
□ 8–12 инсайтов суммарно
□ Минимум 1 инсайт в каждой из 5 категорий
□ applicability — число 0–100 согласно шкале из insight_rules
□ source_types — только значения из разрешённого списка, массив не пустой
□ relatedTo — массив id из существующих требований или пустой массив
□ enhancements — массив объектов { targetType, text }; targetType строго одно из:
  business | functional | nonfunctional
□ Валидный JSON
</self_check>`;
}